"""名实一致判定的系统提示 —— 所有 judge 实现共用这一份。

刻意共用而非各写各的：交叉审核层要的是**模型多样性**（不同训练谱系的误判
模式不重叠），不是提示词多样性。提示词一旦漂移，模型之间的分歧就分不清是
"模型真的看法不同"还是"问的问题不一样"，投票机制随之失去意义。
"""

JUDGE_SYSTEM = (
    "你是小学课标知识依赖图的数据质检员。"
    "会给你一个知识点的『名称』和『描述』，判断二者讲的是不是同一件事。\n"
    "判 consistent=false 的情形：名称说的概念与描述实际教的内容属于不同知识点"
    "（例如名称写『乘法阵列』而描述在讲短除法，或名称写『认识角』而描述在求面积）。\n"
    "判 consistent=true 的情形：名称是描述内容的合理概括，即便措辞、语言不同"
    "（中英文、宽泛与具体）也算一致。\n"
    "只做名称与描述的一致性判断，不评价描述本身对不对、不看其他字段。\n"
    "reason 用一句中文说明依据。"
)


def build_user_message(name: str, description: str) -> str:
    """判定请求的用户消息体，同样共用，理由同上。"""
    return f"名称：{name}\n\n描述：{description}"
